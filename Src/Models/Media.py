from pydantic.v1 import Field, validator
from abc import abstractmethod
from typing import List, Union, Literal, Optional, Any
from tidy3d.components.base import Tidy3dBaseModel
from tidy3d.components.types import ArrayComplex1D, ArrayFloat1D
from skrf.media import (Coaxial, RectangularWaveguide, MLine, CPW, Freespace,
    CircularWaveguide, DefinedGammaZ0, DefinedAEpTandZ0, DistributedCircuit, Media)
from skrf.frequency import Frequency
import numpy as np

class AbstractMedia(Tidy3dBaseModel):
    """Abstract base class for all media components"""
    frequency: ArrayFloat1D = Field(
        ...,
        title="Frequency",
        description="Frequency points in Hz",
        example=[1e9, 2e9, 3e9]
    )
    z0: Optional[Union[complex, ArrayComplex1D]] = Field(
        50,
        title="Characteristic Impedance",
        description="Complex characteristic Impedance (n_freqs, complex)",
        example=50+0j
    )
    z0_port: Optional[Union[complex, ArrayComplex1D]] = Field(
        50,
        title="Port Impedance",
        description="z0_port is the port impedance for networks generated by the media. If z0_port is not None, the networks generated by the media are renormalized (or in other words embedded) from the characteristic impedance Z0 of the media to z0_port. Else if z0_port is None, the networks port impedances will be the raw characteristic impedance Z0 of the media.",
        example=50+0j
    )
    type: Literal['AbstractMedia'] = Field(
        'AbstractMedia',
        title="Type",
        description="Type of media",
        frozen=True
    )

    def __init__(self, **data: Any):
        super().__init__(**data)
    
    @abstractmethod
    def to_rf_media(self) -> Media:
        """Convert to scikit-rf Media object"""
        raise NotImplementedError


class CoaxialLine(AbstractMedia):
    """Coaxial transmission line"""
    dinner: float = Field(
        ...,
        title="Inner Diameter",
        description="Inner conductor diameter, in meters"
    )
    douter: float = Field(
        ...,
        title="Outer Diameter",
        description="Outer conductor diameter, in meters"
    )
    epsilon_r: Optional[float] = Field(
        1.0,
        title="Relative Permittivity",
        description="Relative permittivity of dielectric. Default is 1.0 (air)"
    )
    tan_delta: Optional[float] = Field(
        0.0,
        title="Loss Tangent",
        description="Loss tangent of dielectric. Default is 0.0 (non lossy dielectric)"
    )
    sigma: Optional[float] = Field(
        np.inf,
        title="Conductivity",
        description="Conductors electrical conductivity, in S/m. Default is infinity (non lossy metal)."
    )
    type: Literal['CoaxialLine'] = Field(
        'CoaxialLine',
        title="Type",
        description="Type of transmission line",
        frozen=True
    )

    @validator('dinner')
    def validate_inner_diameter(cls, v):
        if v <= 0:
            raise ValueError("Inner diameter must be positive")
        return v

    @validator('douter')
    def validate_outer_diameter(cls, v, values):
        if v <= 0:
            raise ValueError("Outer diameter must be positive")
        if 'dinner' in values and v <= values['dinner']:
            raise ValueError("Outer diameter must be greater than inner diameter")
        return v

    @validator('epsilon_r')
    def validate_epsilon_r(cls, v):
        if v <= 0:
            raise ValueError("Relative permittivity must be positive")
        return v

    @validator('tan_delta')
    def validate_tan_delta(cls, v):
        if v < 0:
            raise ValueError("Loss tangent must be non-negative")
        return v

    @validator('sigma')
    def validate_sigma(cls, v):
        if v <= 0 and v != float('inf'):
            raise ValueError("Conductivity must be positive or infinity")
        return v

    def to_rf_media(self) -> Coaxial:
        """Convert to scikit-rf Coaxial object"""
        frequency = Frequency.from_f(self.frequency, unit='Hz')
        coax = Coaxial(
            frequency=frequency,
            z0=self.z0,
            Dint=self.dinner,
            Dout=self.douter,
            epsilon_r=self.epsilon_r,
            tan_delta=self.tan_delta,
            sigma=self.sigma
        )
        return coax


class RWG(AbstractMedia):
    """Rectangular waveguide transmission line"""
    a: float = Field(
        1,
        title="Width",
        description="Width of waveguide, in meters. Default is 1."
    )
    b: Optional[float] = Field(
        None,
        title="Height",
        description="Height of waveguide, in meters. If None defaults to a/2. Default is None"
    )
    
    @validator('a')
    def validate_width(cls, v):
        if v <= 0:
            raise ValueError("Width must be positive")
        return v
    
    @validator('b')
    def validate_height(cls, v):
        if v is not None and v <= 0:
            raise ValueError("Height must be positive")
        return v
    
    @validator('m')
    def validate_m(cls, v):
        if v < 0:
            raise ValueError("Mode index m must be non-negative")
        return v
    
    @validator('n')
    def validate_n(cls, v):
        if v < 0:
            raise ValueError("Mode index n must be non-negative")
        return v
    
    @validator('mode_type')
    def validate_mode_type(cls, v):
        if v not in ['TE', 'TM']:
            raise ValueError("Mode type must be either 'TE' or 'TM'")
        return v

    @validator('rho')
    def validate_rho(cls, v):
        if v is not None and v <= 0:
            raise ValueError("Resistivity must be positive")
        return v

    @validator('roughness')
    def validate_roughness(cls, v):
        if v is not None and v <= 0:
            raise ValueError("Roughness must be positive")
        return v

    m: int = Field(
        1,
        title="Horizontal Mode Index",
        description="Mode index along 'a' direction"
    )
    n: int = Field(
        0,
        title="Vertical Mode Index",
        description="Mode index along 'b' direction"
    )
    mode_type: Literal['TE', 'TM'] = Field(
        'TE',
        title="Mode Type",
        description="Mode type, either TE or TM"
    )
    ep_r: Union[float, ArrayFloat1D] = Field(
        1.0,
        title="Relative Permittivity",
        description="Relative permittivity of dielectric. If array-like must be same length as frequency. Default is 1.0"
    )
    mu_r: Union[float, ArrayFloat1D] = Field(
        1.0,
        title="Relative Permeability",
        description="Relative permeability of dielectric. If array-like must be same length as frequency. Default is 1.0"
    )
    rho: Optional[Union[float, ArrayFloat1D]] = Field(
        None,
        title="Resistivity",
        description="Resistivity of conductor (default is copper). If array-like must be same length as frequency. Default is None"
    )
    roughness: Optional[Union[float, ArrayFloat1D]] = Field(
        None,
        title="Surface Roughness",
        description="Resistivity (ohm-m) of the conductor walls. If array-like must be same length as frequency. if str, it must be a key in skrf.data.materials"
    )
    type: Literal['RWG'] = Field(
        'RWG',
        title="Type",
        description="Type of transmission line",
        frozen=True
    )

    def to_rf_media(self) -> RectangularWaveguide:
        """Convert to scikit-rf RectangularWaveguide object"""
        frequency = Frequency.from_f(self.frequency, unit='Hz')
        waveguide = RectangularWaveguide(
            frequency=frequency,
            z0=self.z0,
            a=self.a,
            b=self.b,
            ep_r=self.ep_r,
            mu_r=self.mu_r,
            rho=self.rho,
            mode_type=self.mode_type,
            m=self.m,
            n=self.n,
            roughness=self.roughness
        )
        return waveguide


